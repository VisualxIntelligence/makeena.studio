import { defineCollection } from "astro:content";
import { file, glob } from "astro/loaders";
import { z } from "astro/zod";
import { locales, routeKeys } from "./i18n/config";
import { DIGITAL_SOURCE_TYPES, ID_PATTERN } from "../scripts/provenance/records.mjs";

// Content model (PRD §10.1). Copy that the brief or the founder still has to supply is written as
// `[PLACEHOLDER: …]`; Arabic files are unreviewed drafts until Phase 5 (decision 0005).
// tests/unit/content.test.ts checks that every route has both locales with matching section ids.

const lang = z.enum(locales);
const localized = z.object({ en: z.string(), ar: z.string() });
const anchor = z.string().regex(/^[a-z0-9-]+$/, "lowercase letters, digits and hyphens");

const link = z.object({
  text: z.string(),
  route: z.enum(routeKeys),
  hash: anchor.optional(),
});

const section = z.object({
  /** Anchor id. The same in both locales so the language switch keeps the reader's place. */
  id: anchor,
  /** Mono section label, Western digits: `01 · POSITION`. */
  label: z.string(),
  heading: z.string().optional(),
  body: z.array(z.string()).default([]),
  links: z.array(link).default([]),
});

/** One file per route and locale: src/content/pages/{lang}/{route}.json. */
const pages = defineCollection({
  loader: glob({ pattern: "*/*.json", base: "./src/content/pages" }),
  schema: z.object({
    route: z.enum(routeKeys),
    lang,
    title: z.string(),
    description: z.string(),
    label: z.string(),
    heading: z.string(),
    lede: z.string().optional(),
    sections: z.array(section).default([]),
  }),
});

/** Three lead services (with their own pages) and the register of eight. */
const services = defineCollection({
  loader: file("./src/content/services.json"),
  schema: z.object({
    kind: z.enum(["lead", "register"]),
    order: z.number().int(),
    route: z.enum(routeKeys).optional(),
    /** Provenance asset shown with a lead service. */
    asset: z.string().regex(ID_PATTERN).optional(),
    name: localized,
    summary: localized,
  }),
});

const gates = defineCollection({
  loader: file("./src/content/gates.json"),
  schema: z.object({
    number: z.string().regex(/^0[1-4]$/),
    name: localized,
    description: localized,
  }),
});

/** Corporate register rows on /studio/#register. */
const register = defineCollection({
  loader: file("./src/content/register.json"),
  schema: z.object({
    order: z.number().int(),
    key: localized,
    value: localized,
    /** Identifiers (licence, tax number, phone) stay Western digits and LTR in Arabic. */
    ltr: z.boolean().default(false),
  }),
});

const site = defineCollection({
  loader: file("./src/content/site.json"),
  schema: z.object({
    legalLine: z.string(),
    copyrightHolder: z.string(),
    /** Contact block (PRD §9.6): text, never a photo. `[PLACEHOLDER: …]` until supplied. */
    contact: z.object({
      name: z.string(),
      title: localized,
      phone: z.string(),
      email: z.string(),
      domain: z.string(),
    }),
  }),
});

/**
 * Provenance records (PRD §10.2), one per asset, generated by `npm run provenance` from
 * design/renders/manifest.json + provenance.json. Never hand-edit src/content/assets/.
 */
const assets = defineCollection({
  loader: glob({ pattern: "*.json", base: "./src/content/assets" }),
  schema: z.object({
    id: z.string().regex(ID_PATTERN, "MKN-{SERIES}-{CAM}-{VARIANT}[_{NNNN}]"),
    type: z.enum(["image", "sequence", "video"]),
    status: z.enum(["concept", "production"]),
    concepts: z.array(z.string()),
    digitalSourceType: z.enum(DIGITAL_SOURCE_TYPES as [string, ...string[]]),
    virtualCamera: z
      .object({
        lensMm: z.number().optional(),
        heightM: z.number().optional(),
        headingDeg: z.number().optional(),
        lat: z.number().optional(),
        lon: z.number().optional(),
      })
      .optional(),
    light: z
      .object({
        label: localized,
        timeLocal: z
          .string()
          .regex(/^[0-2][0-9]:[0-5][0-9]$/)
          .optional(),
        sunAzimuthDeg: z.number().optional(),
        sunAltitudeDeg: z.number().optional(),
      })
      .optional(),
    aircraft: z.literal("none").optional(),
    gatesCleared: z.array(z.enum(["01", "02", "03", "04"])),
    /** Web derivatives lose XMP/C2PA: the site only ever says "retained on master file". */
    metadataRetained: z.object({
      iptc: z.boolean(),
      c2pa: z.boolean(),
      on: z.enum(["master", "derivative"]),
      manifestUrl: z.url().optional(),
    }),
    rights: localized,
    caption: localized,
    /** States what is shown and that it is generated (PRD §14). */
    alt: localized,
    arReviewed: z.boolean(),
    /** Internal; never shown publicly unless the founder approves (PRD §10.2). */
    generator: z
      .object({
        service: z.string(),
        model: z.string(),
        jobId: z.string().optional(),
        derivedFrom: z.string().optional(),
      })
      .optional(),
    source: z.object({ file: z.string(), width: z.number().int(), height: z.number().int() }),
  }),
});

export const collections = { pages, services, gates, register, site, assets };
